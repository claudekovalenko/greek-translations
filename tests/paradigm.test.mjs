import { test } from 'node:test';
import assert from 'node:assert/strict';
import { analyzeVerb, conjugate, decline, declineNominal, augment } from '../js/paradigm.js';

const forms = (lemma, tvm) => conjugate(analyzeVerb(lemma), tvm).cells.map((c) => c.forms.join('/'));
const T = (tense, voice, mood) => ({ tense, voice, mood });

test('λύω indicative', () => {
  assert.deepEqual(forms('λύω', T('P', 'A', 'I')), ['λύω', 'λύεις', 'λύει', 'λύομεν', 'λύετε', 'λύουσι(ν)']);
  assert.deepEqual(forms('λύω', T('P', 'M', 'I')), ['λύομαι', 'λύῃ', 'λύεται', 'λυόμεθα', 'λύεσθε', 'λύονται']);
  assert.deepEqual(forms('λύω', T('I', 'A', 'I')), ['ἔλυον', 'ἔλυες', 'ἔλυε(ν)', 'ἐλύομεν', 'ἐλύετε', 'ἔλυον']);
  assert.deepEqual(forms('λύω', T('F', 'A', 'I')), ['λύσω', 'λύσεις', 'λύσει', 'λύσομεν', 'λύσετε', 'λύσουσι(ν)']);
  assert.deepEqual(forms('λύω', T('A', 'A', 'I')), ['ἔλυσα', 'ἔλυσας', 'ἔλυσε(ν)', 'ἐλύσαμεν', 'ἐλύσατε', 'ἔλυσαν']);
  assert.deepEqual(forms('λύω', T('A', 'P', 'I')), ['ἐλύθην', 'ἐλύθης', 'ἐλύθη', 'ἐλύθημεν', 'ἐλύθητε', 'ἐλύθησαν']);
  assert.deepEqual(forms('λύω', T('F', 'P', 'I')), ['λυθήσομαι', 'λυθήσῃ', 'λυθήσεται', 'λυθησόμεθα', 'λυθήσεσθε', 'λυθήσονται']);
  assert.deepEqual(forms('λύω', T('X', 'A', 'I')), ['λέλυκα', 'λέλυκας', 'λέλυκε(ν)', 'λελύκαμεν', 'λελύκατε', 'λελύκασι(ν)']);
  assert.deepEqual(forms('λύω', T('X', 'M', 'I')), ['λέλυμαι', 'λέλυσαι', 'λέλυται', 'λελύμεθα', 'λέλυσθε', 'λέλυνται']);
});

test('λύω other moods', () => {
  assert.deepEqual(forms('λύω', T('A', 'A', 'S')), ['λύσω', 'λύσῃς', 'λύσῃ', 'λύσωμεν', 'λύσητε', 'λύσωσι(ν)']);
  assert.deepEqual(forms('λύω', T('A', 'P', 'S')), ['λυθῶ', 'λυθῇς', 'λυθῇ', 'λυθῶμεν', 'λυθῆτε', 'λυθῶσι(ν)']);
  assert.deepEqual(forms('λύω', T('P', 'A', 'D')), ['λύε', 'λυέτω', 'λύετε', 'λυέτωσαν']);
  assert.deepEqual(forms('λύω', T('A', 'A', 'D')), ['λῦσον', 'λυσάτω', 'λύσατε', 'λυσάτωσαν']);
  assert.deepEqual(forms('λύω', T('A', 'A', 'N')), ['λῦσαι']);
  assert.deepEqual(forms('λύω', T('A', 'P', 'N')), ['λυθῆναι']);
  assert.deepEqual(forms('λύω', T('P', 'M', 'N')), ['λύεσθαι']);
});

