test('εἰμί and unsupported verbs', () => {
  assert.deepEqual(forms('εἰμί', T('P', 'A', 'I')), ['εἰμί', 'εἶ', 'ἐστί(ν)', 'ἐσμέν', 'ἐστέ', 'εἰσί(ν)']);
  assert.deepEqual(forms('εἰμί', T('F', 'M', 'I')), ['ἔσομαι', 'ἔσῃ', 'ἔσται', 'ἐσόμεθα', 'ἔσεσθε', 'ἔσονται']);
  const r = conjugate(analyzeVerb('δίδωμι'), T('P', 'A', 'I'));
  assert.equal(r.cells.length, 0);
  assert.match(r.note, /μι-verbs/);
  const dep = conjugate(analyzeVerb('ἔρχομαι'), T('P', 'A', 'I'));
  assert.match(dep.note, /deponent/);
});

test('augment', () => {
  const nfc = (arr) => arr.map((s) => s.normalize('NFC'));
  assert.deepEqual(nfc(augment('λυ')), ['ἐλυ']);
  assert.deepEqual(nfc(augment('ἀκου')), ['ἠκου']);
  assert.deepEqual(nfc(augment('εὐχ')), ['ηὐχ', 'εὐχ']);
});

test('nouns', () => {
  const f = (l, g) => decline(l, g).cells.map((c) => c.forms[0]);
  assert.deepEqual(f('λόγος', 'M'), ['λόγος', 'λόγου', 'λόγῳ', 'λόγον', 'λόγοι', 'λόγων', 'λόγοις', 'λόγους']);
  assert.deepEqual(f('ἄνθρωπος', 'M'), ['ἄνθρωπος', 'ἀνθρώπου', 'ἀνθρώπῳ', 'ἄνθρωπον', 'ἄνθρωποι', 'ἀνθρώπων', 'ἀνθρώποις', 'ἀνθρώπους']);
  assert.deepEqual(f('θεός', 'M'), ['θεός', 'θεοῦ', 'θεῷ', 'θεόν', 'θεοί', 'θεῶν', 'θεοῖς', 'θεούς']);
  assert.deepEqual(f('δοῦλος', 'M'), ['δοῦλος', 'δούλου', 'δούλῳ', 'δοῦλον', 'δοῦλοι', 'δούλων', 'δούλοις', 'δούλους']);
  assert.deepEqual(f('ἔργον', 'N'), ['ἔργον', 'ἔργου', 'ἔργῳ', 'ἔργον', 'ἔργα', 'ἔργων', 'ἔργοις', 'ἔργα']);
  assert.deepEqual(f('ζωή', 'F'), ['ζωή', 'ζωῆς', 'ζωῇ', 'ζωήν', 'ζωαί', 'ζωῶν', 'ζωαῖς', 'ζωάς']);
  assert.deepEqual(f('ἡμέρα', 'F'), ['ἡμέρα', 'ἡμέρας', 'ἡμέρᾳ', 'ἡμέραν', 'ἡμέραι', 'ἡμερῶν', 'ἡμέραις', 'ἡμέρας']);
  assert.deepEqual(f('δόξα', 'F'), ['δόξα', 'δόξης', 'δόξῃ', 'δόξαν', 'δόξαι', 'δοξῶν', 'δόξαις', 'δόξας']);
  assert.deepEqual(f('ἀλήθεια', 'F'), ['ἀλήθεια', 'ἀληθείας', 'ἀληθείᾳ', 'ἀλήθειαν', 'ἀλήθειαι', 'ἀληθειῶν', 'ἀληθείαις', 'ἀληθείας']);
  assert.deepEqual(f('προφήτης', 'M'), ['προφήτης', 'προφήτου', 'προφήτῃ', 'προφήτην', 'προφῆται', 'προφητῶν', 'προφήταις', 'προφήτας']);
  assert.match(decline('πατήρ', 'M').note, /first and second declension/);
});

test('fixed nominals and adjectives', () => {
  assert.deepEqual(declineNominal('ὁ', 'RA', 'F').cells.map((c) => c.forms[0]), ['ἡ', 'τῆς', 'τῇ', 'τήν', 'αἱ', 'τῶν', 'ταῖς', 'τάς']);
  assert.deepEqual(declineNominal('αἰώνιος', 'A-', 'N').cells.map((c) => c.forms[0]), ['αἰώνιον', 'αἰωνίου', 'αἰωνίῳ', 'αἰώνιον', 'αἰώνια', 'αἰωνίων', 'αἰωνίοις', 'αἰώνια']);
  assert.match(declineNominal('μονογενής', 'A-', 'M').note, /not generated/);
});
